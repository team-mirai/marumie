/**
 * 領収書の画像から、公開前に黒塗りする個人情報の位置を探させるプロンプト。
 * 塗る対象の定義はここに決め打ちで持つ（事務所ごとの調整や画面からの編集はまだしない）。
 */
export function buildPersonalInfoMaskingPrompt(width: number, height: number): string {
  return `あなたは、議員の調査研究費の領収書を一般に公開する前に、個人情報を黒塗りする担当者です。
渡された画像は、領収書・レシート・請求書などの書類の 1 ページです。画像の大きさは 幅 ${width} 画素 × 高さ ${height} 画素 です。

■ 塗る対象
- 議員本人の電話番号（携帯電話・自宅・事務所の直通など、書類の宛先側に書かれた電話番号）
- 議員本人の住所（自宅・宿舎など。郵便番号を含む）
- 議員以外の個人（宿泊者・同行者・送付先の個人など）の住所・電話番号・郵便番号
- 個人のメールアドレス

■ 塗らない対象
- 店舗・事業者・発行元（領収書を発行した側）の名称・住所・電話番号・登録番号
- 議員の氏名、宛名の名称、日付、金額、品目、但し書き

■ 出力
- 塗る対象の文字列ごとに、それを囲む矩形を regions に 1 件ずつ出す。座標は画像の左上を原点とする画素単位で、x・y は矩形の左上、width・height は矩形の幅と高さ。
- 文字の端が切れないよう、文字列全体を少し余裕をもって囲む。住所が複数行にわたるときは、行ごとに矩形を分けるか、全行をまとめて囲む。
- 「住所」「TEL」などの見出しの文字は塗らなくてよい。値の部分を必ず囲む。
- 塗る対象か迷うものは塗る側に倒す。ただし、発行元の情報は塗らない。
- 塗る対象が無ければ regions を空にする。
- label には塗る理由を短く書く（例：「議員の電話番号」「宿泊者の住所」）。`;
}
