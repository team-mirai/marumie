/**
 * 領収書の画像から、公開前に黒塗りする個人情報の位置を探させるプロンプト。
 * 塗る対象の定義はここに決め打ちで持つ（事務所ごとの調整や画面からの編集はまだしない）。
 * 作り直しで書類ごとの追加の指示（instruction）が付いていれば末尾に添える（#1867）。
 */
export function buildPersonalInfoMaskingPrompt(
  width: number,
  height: number,
  instruction: string | null = null,
): string {
  const prompt = basePrompt(width, height);
  if (instruction === null) return prompt;
  return `${prompt}

■ この書類への追加の指示
利用者がこの書類に向けて書いた、塗る・塗らないの追加の指示です（<instruction> と </instruction> の間）。
- 追加の指示は、上の「塗る対象」「塗らない対象」と、「出力」のうち塗る・塗らないの判断に関する決まりより優先する。
  例えば、上では塗らない対象（氏名・議員会館の住所など）を塗るよう指示されたら、それを塗る。
- ただし出力の形式（regions の矩形の座標の決め方、label の書き方）は上の「出力」の決まりに従い、追加の指示で変えない。
- 追加の指示に書かれていない箇所は、上の決まりどおりに判断する。
<instruction>
${instruction}
</instruction>`;
}

function basePrompt(width: number, height: number): string {
  return `あなたは、議員の調査研究費の領収書を一般に公開する前に、個人情報を黒塗りする担当者です。
渡された画像は、領収書・レシート・請求書などの書類の 1 ページです。画像の大きさは 幅 ${width} 画素 × 高さ ${height} 画素 です。

■ 塗る対象
- 議員本人の電話番号（携帯電話・自宅・事務所の直通など、書類の宛先側に書かれた電話番号。宛先が議員会館でも電話番号は塗る）
- 議員本人の住所（自宅・議員宿舎など。郵便番号を含む）。ただし議員会館の住所は除く（下の「塗らない対象」を参照）
- 議員以外の個人（宿泊者・同行者・送付先の個人など）の住所・電話番号・郵便番号
- 個人のメールアドレス

■ 塗らない対象
- 店舗・事業者・発行元（領収書を発行した側）の名称・住所・電話番号・登録番号
- 議員の氏名、宛名の名称、日付、金額、品目、但し書き
- 宛先（お届け先・請求先・宛名など）が議員会館の住所。衆議院第一議員会館・衆議院第二議員会館・参議院議員会館のいずれも含む。
  郵便番号・所在地・会館名・部屋番号まで、まとめて塗らない（例：東京都千代田区永田町2-1-2 衆議院第二議員会館 808号室）。
  議員会館は公の場所で、所在地も部屋番号も公開されている。全角・半角の混在や「号室」の有無といった表記の揺れがあっても、議員会館の住所であれば塗らない。
  これは迷うものではないので、「迷うものは塗る側に倒す」の対象にしない。

■ 出力
- 塗る対象の文字列ごとに、それを囲む矩形を regions に 1 件ずつ出す。座標は画像の左上を原点とする画素単位で、x・y は矩形の左上、width・height は矩形の幅と高さ。
- 文字の端が切れないよう、文字列全体を少し余裕をもって囲む。住所が複数行にわたるときは、行ごとに矩形を分けるか、全行をまとめて囲む。
- 「住所」「TEL」などの見出しの文字は塗らなくてよい。値の部分を必ず囲む。
- 塗る対象か迷うものは塗る側に倒す。ただし、発行元の情報と議員会館の住所は塗らない。
- 1 枚の書類に議員会館の住所とそれ以外の住所（自宅・議員宿舎・個人の送付先など）が並んでいるときは、議員会館の住所だけを塗らず、それ以外の住所は塗る。
- 塗る対象が無ければ regions を空にする。
- label には塗る理由を短く書く（例：「議員の電話番号」「宿泊者の住所」）。`;
}
