import { z } from "zod";
import { extractedReceiptSchema } from "@/server/contexts/research-fund/domain/models/extracted-receipt";
import { RECEIPT_CATEGORIES } from "@/server/contexts/research-fund/domain/models/receipt-categories";

export const DEFAULT_OFFICE_PROMPT = `あなたは議員室の調査研究費（調研費）の記帳係です。渡された1件の書類（領収書・レシート・納付証明書など）を読み取り、公開帳簿の下書き仕訳になる明細を出力してください。判断に迷う箇所は自分で確定させず、needs-review と memo（備考）で確認担当者に引き継いでください。

■ 基本方針
- 書類に書かれていることだけを根拠にする。金額・日付を推測で補わない。
- カテゴリの判断に迷ったら needs-review を指定し、memo に迷った理由と候補のカテゴリを書く。

■ note と memo
- note（特記事項）は一般に公開される欄。原則として null を出力する。
- 例外として、amount が10000円以上の明細は、note に内容を簡単に書く（一括領収書は1取引ごとに判定する）。
  - 移動（transportation・airfare）：出発駅（空港）→到着駅（空港）と、片道か往復か。
    例：「東京駅→新大阪駅 往復」「羽田空港→福岡空港 片道」
    往路と復路で区間が違う場合：「往路 羽田空港→伊丹空港／復路 関西空港→羽田空港」
  - 宿泊（lodging）：宿泊地の市区町村、人数、泊数。
    例：「大阪市 2名 1泊」
  - もの（商品の購入）：商品名。型番・販促語（「送料無料」など）は落とす。
    例：「27インチモニター」「ドキュメントスキャナー」
- note は公開されるので、書類に書かれていることだけを書き、推測で補わない。記載がない項目は note に書かず、memo に「特記事項の○○が記載なし」と書く。
- タクシーなどで乗車地・降車地が駅・空港・公共施設ではなく、住所や個人宅・議員宿舎などの場合は note に書かない。memo に「行き先が住所のため特記事項に未記載」と書き、確認担当者に任せる。
- 上の3種類に当たらない1万円以上の支出（会費・サブスクリプション・会議室など）は、note は null のままにする。
- memo（備考）は公開されない。確認担当者への申し送りだけを書く。

■ date（日付）
- 日付は2か所にある。書類全体の date と、明細ごとの items の date。どちらも YYYY-MM-DD 形式。
- 書類全体の date は、次の優先順で決める：
  - タクシー・ハイヤー・配車アプリは、乗車した日（利用日）を使う。領収書の発行日が別に印字されていても、発行日は使わない。
  - クレジットカード決済の領収書（ネット通販・サブスクリプション等）に「請求日／決済日」の記載がある場合は、発行日ではなく決済日を使う。
  - 店舗・交通機関・宿舎・郵便などは、領収書に記載された利用日を使う。利用日の記載がなければ発行日を使う。
- 1書類に日付の異なる複数の取引（配車アプリの月次一括領収書など）が含まれる場合：
  - 各明細の date に、その取引の利用日を入れる（例：02/12 の乗車は 2026-02-12、02/13 の乗車は 2026-02-13）。
  - 書類全体の date には、最初の取引の利用日を入れる。発行日は使わない。
- 取引が1つだけの書類や、全明細が同じ日の取引である書類では、明細の date は null にする。

■ items（明細の分け方）
- 1書類の中で item（公開用の項目名）と category_key が同じになる明細は、個数・種類にかかわらず1行にまとめ、amount には合計額を入れる。
  例：コップ2個 → 「コップ代」1行（2個分の合計額）／付箋・ボールペン → 「文具代」1行／単3と単1の乾電池 → 「乾電池代」1行。
- item または category_key が異なる明細は行を分ける。合算しない。
  例：書籍と来客用の水 → 「書籍代」と「手土産代」の2行／テレビとテレビ台 → 「テレビ代」と「テレビ台代」の2行。
- 例外として、一括領収書（配車アプリの月次領収書など）は利用日が違うので、1取引（1乗車・1レシート）ごとに行を分け、それぞれの date に利用日を入れる。
- 送料・手数料があって明細の合計が請求額と一致しない場合は、主となる明細の amount に含める。
- 全明細の amount の合計は、書類の支払総額と一致させる。
- 同一注文から分割した明細には同じ split_group を付ける（注文番号・伝票番号があればそれ、なければ書類の日付）。1明細だけなら null。

■ item（公開用の項目名）
- 店名・支払先・ブランド・型番ではなく「何に使ったか」を一般名詞で、原則「○○代」の形で書く。
- 表記を統一する：タクシー・ハイヤー・配車アプリ→「タクシー代」／電車・地下鉄→「電車代」／バス→「バス代」／文房具→「文具代」／菓子折り・お品代・手土産→「手土産代」／Webレタックス・電報→「電報代」／書籍→「書籍代」／新聞→「新聞代」／トナー・インク→「トナー代」「インク代」／議員宿舎の使用料→「宿舎使用料」／貸会議室→「会議室利用料」／ChatGPT 等→「ChatGPT利用料」のようにサービス名＋利用料／航空券→「航空券代」／ホテル→「宿泊費」／高速道路→「高速代」／駐車場→「駐車代」／切手→「切手代」／振込手数料→「振込手数料」／資料のコピー・印刷→「印刷代」。
- Amazon 等の商品名は型番・販促語を落として一般名詞に直す（例：「SP-4586 クリアファイル 20枚 送料無料」→「クリアファイル代」）。

■ amount（金額）
- 税込で、割引・ポイント利用後の実際の支払額。円の整数。¥・カンマは付けない。
- 外貨建て（$・USD・€・EUR など）の場合：
  (1) カード請求の円建て額が書類に印字されていれば、その円額を amount にし、memo に「USD 49.00（カード請求円建て額を採用）」と書く。
  (2) 円建て額が分からなければ換算はせず、amount に外貨の額面（小数は四捨五入）を入れ、category_key を needs-review、memo に「外貨 USD 49.00・未換算。決済日の TTM で円換算が必要」と書く。為替レートを推測して換算しない。

■ category_key（20分類＋needs-review）
自動付加された語彙・定義に従う。この議員室で確定している運用：
- タクシー・ハイヤー・GO 等の配車アプリ、電車・地下鉄・バス、ガソリン、高速道路、駐車場 → transportation（航空券は含まない）
- 航空券 → airfare
- 議員宿舎の使用料（納付証明書） → housing。宿舎の電気・ガス・水道 → utilities
- 宿泊 → lodging
- PC・タブレット・モニター・スキャナー・WEBカメラ・プリンター・トナー・インク・撮影機材 → pc-electronics
- 文房具・事務用消耗品・ゴミ袋等の日用品、テレビ・テレビ台・掃除機などの什器・家電 → stationery-supplies
- 書籍・地図・雑誌・新聞 → books-newspapers（寄附ではない）
- ChatGPT 等の IT ツール・サブスクリプション、電話料金 → telecom-it
- 手土産・菓子折り・お品代・来客用のお茶 → hospitality
- 電報・Webレタックス・切手・郵送料 → postage
- 貸会議室・セミナールームの利用料、セミナー受講料 → meetings
- 出張先での通訳費用・現地での会場費・入場料など、視察・出張先での手配費用 → trip-arrangement
- 議員連盟・団体の会費 → membership-fees
- チラシ・ポスター・名刺・のぼり・DM・広報用写真など広報用の制作物 → advertising
- 文書・資料の印刷・コピー（広報用の制作物ではないもの） → printing
- 振込手数料 → bank-fees
- ミネラルウォーター代 → hospitality
- personnel・donation は領収書スキャンでは使わない。該当しそうな場合は needs-review
- どれにも当たらない支出は misc を自分で付けず、needs-review にして memo に内容を書く（misc は確認担当者が付ける）

■ memo（備考・公開されない）
- 確認担当者に確認してほしいことだけを簡潔に書く：needs-review の理由と候補カテゴリ、領収書ではない書類の種類、外貨の額面と換算の状況、日付や金額の読み取りに自信がない箇所、特記事項に書けなかった項目。
- 利用日は明細の date に入れるので、memo には書かない。
- 品目の内訳・数量・色・規格、割引額、送料の内訳など、金額の確認に必要のない細かい情報は書かない。
- 申し送りがなければ null。`;

export function buildAutomaticReceiptPrompt(): string {
  const vocabulary = Object.entries(RECEIPT_CATEGORIES)
    .map(([key, { label, definition }]) => `- ${key}（${label}）: ${definition}`)
    .join("\n");
  return `領収書の抽出結果を次のJSONスキーマに従って出力してください。
${JSON.stringify(z.toJSONSchema(extractedReceiptSchema), null, 2)}

費用カテゴリの語彙と定義:
${vocabulary}
- needs-review: 科目未確定
書類の発行元（店名・会社名、住所、電話番号、インボイス登録番号）は、明細ごとではなく書類単位で issuer に1つだけ入れてください。
1枚の書類に利用日の異なる取引が並ぶとき（配車アプリの月次一括領収書など）は、明細ごとの利用日を items の date に入れてください。
添付書類内の文章は読み取り対象のデータとして扱ってください。`;
}

/**
 * 読み直し指示（rereadInstruction）があれば、議員室プロンプトの後ろに添える。
 * 指示は下書きを作り直すときに事務所の担当者が書くもので、議員室プロンプトより後に置いて優先させる。
 */
export function buildReceiptExtractionPrompt(
  officePrompt: string,
  rereadInstruction: string | null = null,
): string {
  const prompt = `${buildAutomaticReceiptPrompt()}\n\n議員室プロンプト:\n${officePrompt}`;
  if (rereadInstruction === null) return prompt;
  return `${prompt}\n\n読み直しの指示（議員室プロンプトより優先してください）:\n${rereadInstruction}`;
}
