/**
 * 書類の公開用の版を、画面を開いているかどうかに関係なくサーバー側で作るきっかけ（#1812）。
 * メッセージには書類を指定せず、受け取った処理が DB から pending の書類を選んで 1 件作る。
 * 同じメッセージが 2 回届いても、DB で着手を取り合うので同じ書類を二重に作らない。
 */
export interface DocumentMaskingQueue {
  /** キューを使えるか。使えない環境（ローカル・CI・E2E）では false で、notify は何もしない */
  readonly enabled: boolean;
  /**
   * pending の書類を 1 件作るよう依頼する。失敗しても例外は投げない
   * （積めなかった分は定期実行が拾い直すので、呼び出し元の登録や依頼を失敗させない）
   */
  notify(): Promise<void>;
}
